"""
Port_Config.py - PORT Configuration Validator & Generator

Purpose
-------
Port_Config is a production-oriented Cisco IOS/IOS-XE port configuration utility.
It validates requested switch ports with read-only SSH commands, generates local
implementation configuration from a simple per-port template, captures PRE/POST
evidence, optionally saves running-config backups, and can create a consolidated
HTML Side-by-Side PRE/POST comparison report.

Version 5 Input and Execution Model
---------------------
The implementation template is intentionally independent of VLAN discovery.
It contains only the commands that belong INSIDE an interface configuration.
For example::

    description UNUSED_PORT
    shutdown

Port_Config adds the device and interface structure automatically::

    Device_Name:Switch1
    config t
    !
    interface GigabitEthernet1/0/1
     description UNUSED_PORT
     shutdown
    exit
    !
    interface GigabitEthernet1/0/2
     description UNUSED_PORT
     shutdown
    exit
    end
    wr
    !
    show interfaces GigabitEthernet1/0/1 status
    show mac address-table interface GigabitEthernet1/0/1
    !

Inventory can be supplied either through a CSV containing hostname/port columns
or directly on the command line with --host and --Port. A MAC column remains
optional for backward compatibility and endpoint validation, but is no longer
required.

Safety Model
------------
NORMAL GENERATION AND CHECK MODES ARE READ-ONLY.

Read-only collection commands pass through send_read_only_command(), which
rejects any command that does not begin with ``show ``. Configuration is sent
only when the operator explicitly uses ``--execute <config-file>``. Execution
parses Device_Name delimiters, applies only active interface-level commands,
saves the configuration, and runs the embedded validation show commands.
SSH known_hosts files are not used.

Maintenance Guidelines
----------------------
- Keep read-only collection behind send_read_only_command().
- Keep configuration deployment centralized in run_execute()/execute_device_plan().
- Keep interface normalization centralized in normalize_interface_name().
- The port template is a Jinja2 interface-body template. Keep rendering logic
  centralized in template_context()/render_template() and do not reintroduce
  required VLAN placeholders.
- Structural commands (interface/config t/end/wr) are generated by the program,
  not supplied by the per-port template. Generated files also contain read-only
  validation commands after ``wr``.
- If snapshot JSON structure changes, increment the schema and preserve backward
  compatibility where practical.
- HTML comparison output is self-contained and requires no web server.

Author: Peskicorp
Python: 3.10+
Version: 5.1.0

Runtime Requirements
--------------------
    pip install netmiko rich ntc-templates jinja2
"""




