def parse_execution_file(path: Path) -> list[ExecutionDevicePlan]:
    """Parse a generated Port_Config config file into per-device execution plans.

    Device sections are delimited by ``Device_Name:<hostname>``. Commented lines
    are ignored, making previously safety-commented port blocks non-executable.
    Only interface-level configuration is accepted; arbitrary global configuration
    outside interface mode is rejected.
    """
    if not path.is_file():
        raise FileNotFoundError(f"Execution file not found: {path}")
    raw_lines = path.read_text(encoding="utf-8-sig").splitlines()
    plans: list[ExecutionDevicePlan] = []
    current: ExecutionDevicePlan | None = None
    in_interface = False
    seen_switches: set[str] = set()

    def finish_current() -> None:
        nonlocal current, in_interface
        if current is None:
            return
        if in_interface:
            raise ValueError(f"{current.switch}: interface block is missing exit")
        if current.switch.lower() in seen_switches:
            raise ValueError(f"Duplicate Device_Name section: {current.switch}")
        seen_switches.add(current.switch.lower())
        plans.append(current)
        current = None

    for line_no, raw in enumerate(raw_lines, start=1):
        stripped = raw.strip()
        if not stripped or stripped.startswith("!"):
            continue
        device_match = re.fullmatch(r"Device_Name\s*:\s*(.+)", stripped, flags=re.I)
        if device_match:
            finish_current()
            switch = device_match.group(1).strip()
            if not switch:
                raise ValueError(f"Line {line_no}: empty Device_Name")
            current = ExecutionDevicePlan(switch=switch)
            in_interface = False
            continue
        if current is None:
            raise ValueError(f"Line {line_no}: command appears before Device_Name delimiter: {stripped}")

        low = stripped.lower()
        if low in {"config t", "configure terminal"}:
            if in_interface:
                raise ValueError(f"Line {line_no}: config t found inside interface mode")
            continue
        if low == "end":
            if in_interface:
                raise ValueError(f"Line {line_no}: end found before interface exit")
            continue
        if low in {"wr", "write memory"}:
            if in_interface:
                raise ValueError(f"Line {line_no}: save command found inside interface mode")
            current.save_config = True
            continue
        if low.startswith("show "):
            if in_interface:
                raise ValueError(f"Line {line_no}: show command found inside interface mode")
            current.validation_commands.append(stripped)
            continue
        if re.match(r"^interface\s+\S+", stripped, flags=re.I):
            if in_interface:
                raise ValueError(f"Line {line_no}: nested interface command is not allowed")
            port = stripped.split(None, 1)[1].strip()
            try:
                port = normalize_interface_name(port)
            except ValueError as exc:
                raise ValueError(f"Line {line_no}: {exc}") from exc
            current.config_commands.append(f"interface {port}")
            if port not in current.interfaces:
                current.interfaces.append(port)
            in_interface = True
            continue
        if low == "exit":
            if not in_interface:
                raise ValueError(f"Line {line_no}: exit found outside interface mode")
            current.config_commands.append("exit")
            in_interface = False
            continue

        if not in_interface:
            raise ValueError(
                f"Line {line_no}: unsupported global configuration command {stripped!r}. "
                "Port_Config execution accepts interface-level config only."
            )
        current.config_commands.append(stripped)

    finish_current()
    if not plans:
        raise ValueError("Execution file does not contain any Device_Name sections")
    return plans


def preflight_execute_devices(
    plans: list[ExecutionDevicePlan], username: str, password: str, timeout: int, logger: logging.Logger
) -> list[DeviceConnectionError]:
    """Validate SSH authentication/reachability for every execution target before changes."""
    failures: list[DeviceConnectionError] = []
    for plan in plans:
        connection = None
        try:
            connection = ConnectHandler(**connection_params(plan.switch, username, password, timeout))
            send_read_only_command(connection, "show clock")
        except NetmikoAuthenticationException as exc:
            failures.append(DeviceConnectionError(plan.switch, "AUTHENTICATION FAILED", str(exc)))
        except NetmikoTimeoutException as exc:
            failures.append(DeviceConnectionError(plan.switch, "CONNECTION TIMEOUT", str(exc)))
        except Exception as exc:
            failures.append(DeviceConnectionError(plan.switch, "CONNECTION FAILED", str(exc)))
        finally:
            if connection is not None:
                try:
                    connection.disconnect()
                except Exception:
                    logger.debug("Preflight disconnect failed for %s", plan.switch, exc_info=True)
    return failures


def execute_device_plan(
    plan: ExecutionDevicePlan,
    *,
    username: str,
    password: str,
    timeout: int,
    logger: logging.Logger,
) -> tuple[str, list[tuple[str, str]]]:
    """Apply one parsed device plan, save it, then run embedded validation commands."""
    connection = None
    validations: list[tuple[str, str]] = []
    try:
        connection = ConnectHandler(**connection_params(plan.switch, username, password, timeout))
        logger.warning("EXECUTION START | Switch=%s | Interfaces=%s", plan.switch, ",".join(plan.interfaces))
        if plan.config_commands:
            connection.send_config_set(
                plan.config_commands,
                read_timeout=max(timeout, 60),
                cmd_verify=True,
                error_pattern=r"(?im)^%\s*(?:Invalid input|Incomplete command|Ambiguous command|Error|Failed)",
            )
        if plan.save_config:
            connection.save_config()
        for command in plan.validation_commands:
            output = send_read_only_command(connection, command, read_timeout=max(timeout, 60))
            validations.append((command, output))
            logger.info("EXECUTION VALIDATION | Switch=%s | Command=%s\n%s", plan.switch, command, output)
        logger.warning("EXECUTION COMPLETE | Switch=%s", plan.switch)
        return "SUCCESS", validations
    finally:
        if connection is not None:
            try:
                connection.disconnect()
            except Exception:
                logger.debug("Execution disconnect failed for %s", plan.switch, exc_info=True)


def run_execute(args: argparse.Namespace, password: str, logger: logging.Logger) -> int:
    """Execute a generated single-device or multi-device Port_Config config file."""
    path = Path(args.execute)
    plans = parse_execution_file(path)
    print_main_banner()
    console.print(f"Execution File : {path}")
    console.print(f"Devices        : {len(plans)}\n")

    table = Table(show_lines=False, header_style="bold")
    table.add_column("Device")
    table.add_column("Interfaces", justify="right")
    table.add_column("Config Commands", justify="right")
    table.add_column("Validation", justify="right")
    for plan in plans:
        table.add_row(plan.switch, str(len(plan.interfaces)), str(len(plan.config_commands)), str(len(plan.validation_commands)))
    console.print(table)

    failures = preflight_execute_devices(plans, args.username, password, args.timeout, logger)
    if failures:
        console.print("\nPRE-FLIGHT FAILED - NO CONFIGURATION WAS EXECUTED")
        error_table = Table(header_style="bold red")
        error_table.add_column("Device")
        error_table.add_column("Failure")
        for exc in failures:
            error_table.add_row(exc.switch, exc.category)
        console.print(error_table)
        return 3

    if not args.yes:
        console.print("\nWARNING: --execute will modify switch configuration and may shut down interfaces.")
        answer = input("Type EXECUTE to continue: ").strip()
        if answer != "EXECUTE":
            console.print("Execution cancelled. No configuration was changed.")
            return 0

    result_table = Table(header_style="bold")
    result_table.add_column("Device")
    result_table.add_column("Result")
    result_table.add_column("Interfaces")
    result_table.add_column("Validation Commands")

    for plan in plans:
        try:
            status, validations = execute_device_plan(
                plan,
                username=args.username,
                password=password,
                timeout=args.timeout,
                logger=logger,
            )
            result_table.add_row(plan.switch, status, str(len(plan.interfaces)), str(len(validations)))
        except Exception as exc:
            logger.exception("Execution failed for %s", plan.switch)
            result_table.add_row(plan.switch, "FAILED", str(len(plan.interfaces)), "0")
            console.print(result_table)
            console.print(f"\nERROR: Execution stopped on {plan.switch}: {exc}")
            console.print("Review Port_Config.log and verify the device before continuing.")
            return 4

    console.print("\n")
    console.print(result_table)
    console.print("\nExecution completed. Validation command output is stored in Port_Config.log.")
    return 0


