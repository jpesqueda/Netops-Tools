def normalize_mac(value: str) -> str:
    """Normalize supported MAC address formats to Cisco dotted-lowercase notation.
    
    Raises ValueError when the supplied value does not contain exactly twelve
    hexadecimal digits."""
    compact = re.sub(r"[^0-9A-Fa-f]", "", value or "")
    if len(compact) != 12 or not re.fullmatch(r"[0-9A-Fa-f]{12}", compact):
        raise ValueError(f"Invalid MAC address: {value!r}")
    compact = compact.lower()
    return f"{compact[0:4]}.{compact[4:8]}.{compact[8:12]}"


def normalize_interface_name(name: str) -> str:
    """Normalize and validate common Cisco interface names safely.

    The previous implementation used a regular-expression alternation such as
    ``(?:gi|gig|gigabitethernet)``.  Because regex alternations are evaluated
    left-to-right, a full name like ``GigabitEthernet1/1/1`` matched the short
    ``gi`` prefix first and produced an invalid duplicated name such as
    ``GigabitEthernetgabitEthernet1/1/1``.

    This implementation avoids partial-prefix replacement entirely.  It splits
    the interface into an alphabetic interface type and a numeric interface ID,
    then maps the complete interface type to one canonical Cisco name.

    Accepted examples include::

        Gi1/0/1
        Gig1/0/1
        GigabitEthernet1/0/1
        Te1/0/1
        TenGigabitEthernet1/0/1
        TwentyFiveGigE1/0/1
        Fo1/0/1
        FortyGigabitEthernet1/0/1
        Hu1/0/1
        HundredGigabitEthernet1/0/1

    A malformed or unsupported interface raises ``ValueError`` instead of being
    silently passed to a Cisco show command.
    """
    raw = re.sub(r"\s+", "", (name or "").strip())
    if not raw:
        raise ValueError("Interface name cannot be empty")

    # Split the complete interface type from the numeric interface identifier.
    # Requiring the suffix to begin with a digit prevents partial-prefix matches.
    match = re.fullmatch(r"([A-Za-z][A-Za-z-]*)(\d+(?:/\d+)*(?:\.\d+)?)", raw)
    if not match:
        raise ValueError(f"Invalid Cisco interface format: {name!r}")

    interface_type, interface_id = match.groups()
    key = interface_type.lower()

    # IMPORTANT: keys represent complete interface-type tokens, not prefixes.
    aliases = {
        # Gigabit Ethernet
        "gi": "GigabitEthernet",
        "gig": "GigabitEthernet",
        "gigabit": "GigabitEthernet",
        "gigabitethernet": "GigabitEthernet",

        # Ten Gigabit Ethernet
        "te": "TenGigabitEthernet",
        "ten": "TenGigabitEthernet",
        "tengig": "TenGigabitEthernet",
        "tengigabitethernet": "TenGigabitEthernet",

        # Twenty-Five Gigabit Ethernet
        "tw": "TwentyFiveGigE",
        "twe": "TwentyFiveGigE",
        "twentyfivegige": "TwentyFiveGigE",
        "twentyfivegigabitethernet": "TwentyFiveGigE",

        # Forty Gigabit Ethernet
        "fo": "FortyGigabitEthernet",
        "fortygigabitethernet": "FortyGigabitEthernet",

        # Hundred Gigabit Ethernet
        "hu": "HundredGigabitEthernet",
        "hundredgige": "HundredGigabitEthernet",
        "hundredgigabitethernet": "HundredGigabitEthernet",

        # Common legacy/access interface types.
        "fa": "FastEthernet",
        "fastethernet": "FastEthernet",
        "eth": "Ethernet",
        "ethernet": "Ethernet",
    }

    canonical_type = aliases.get(key)
    if canonical_type is None:
        raise ValueError(f"Unsupported Cisco interface type: {interface_type!r}")

    return f"{canonical_type}{interface_id}"


def interface_short_name(name: str) -> str:
    """Return a Cisco-style short interface name used when matching show-command output."""
    replacements = [
        ("GigabitEthernet", "Gi"),
        ("TenGigabitEthernet", "Te"),
        ("TwentyFiveGigE", "Twe"),
        ("FortyGigabitEthernet", "Fo"),
        ("HundredGigabitEthernet", "Hu"),
    ]
    for long_name, short_name in replacements:
        if name.lower().startswith(long_name.lower()):
            return short_name + name[len(long_name):]
    return name


def normalize_csv_header(value: str) -> str:
    """Normalize a CSV header for tolerant, case-insensitive alias matching.

    Spaces, underscores, and hyphens are ignored. This allows operational teams
    to use common English or Spanish column names without changing the internal
    data model.
    """
    return re.sub(r"[\s_-]+", "", (value or "").strip().lower())


def read_hosts_csv(path: Path) -> list[InputRecord]:
    """Load and validate a CSV inventory with tolerant English/Spanish headers.

    Required semantic fields:
        hostname/switch/host/device/equipo
        puerto/port/interface/interfaz

    An optional MAC column is accepted for backward compatibility and endpoint
    validation. When omitted, MAC validation is reported as NOT_PROVIDED.
    """
    if not path.is_file():
        raise FileNotFoundError(f"Host file not found: {path}")

    alias_to_semantic = {
        "switch": "Switch", "hostname": "Switch", "host": "Switch",
        "device": "Switch", "equipo": "Switch",
        "port": "Port", "puerto": "Port", "interface": "Port", "interfaz": "Port",
        "mac": "MAC", "macaddress": "MAC", "direccionmac": "MAC", "direcciónmac": "MAC",
    }

    records: list[InputRecord] = []
    seen: set[tuple[str, str]] = set()

    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        if not reader.fieldnames:
            raise ValueError("Host CSV is empty or does not contain a header row")

        columns: dict[str, str] = {}
        for original_header in reader.fieldnames:
            semantic = alias_to_semantic.get(normalize_csv_header(original_header))
            if semantic is None:
                continue
            if semantic in columns:
                raise ValueError(
                    f"Host CSV contains multiple columns mapped to {semantic}: "
                    f"{columns[semantic]!r} and {original_header!r}"
                )
            columns[semantic] = original_header

        missing = [name for name in ("Switch", "Port") if name not in columns]
        if missing:
            raise ValueError(
                "Host CSV is missing required column(s): " + ", ".join(missing)
                + ". Example: hostname,puerto"
            )

        for line_no, row in enumerate(reader, start=2):
            switch = (row.get(columns["Switch"]) or "").strip()
            raw_port = (row.get(columns["Port"]) or "").strip()
            raw_mac = (row.get(columns["MAC"]) or "").strip() if "MAC" in columns else ""

            # Silently skip completely empty lines often left at the end of CSV files.
            if not switch and not raw_port and not raw_mac:
                continue
            if not switch:
                raise ValueError(f"Line {line_no}: hostname/switch is required")

            try:
                port = normalize_interface_name(raw_port)
            except ValueError as exc:
                raise ValueError(f"Line {line_no}: {exc}") from exc

            mac = ""
            if raw_mac:
                try:
                    mac = normalize_mac(raw_mac)
                except ValueError as exc:
                    raise ValueError(f"Line {line_no}: {exc}") from exc

            key = (switch.lower(), port.lower())
            if key in seen:
                raise ValueError(f"Line {line_no}: duplicate hostname/port: {switch},{port}")
            seen.add(key)
            records.append(InputRecord(switch=switch, port=port, mac=mac))

    if not records:
        raise ValueError("Host CSV contains no data rows")
    return records


def build_direct_records(host: str, port_groups: list[list[str]] | None) -> list[InputRecord]:
    """Create normalized inventory records from --host and one/more --Port values."""
    if not host:
        raise ValueError("Direct mode requires --host")
    raw_ports: list[str] = []
    for group in port_groups or []:
        for item in group:
            # Accept both space-separated and comma-separated port lists.
            raw_ports.extend(part.strip() for part in item.split(",") if part.strip())

    if not raw_ports:
        raise ValueError("Direct mode requires at least one --Port")

    records: list[InputRecord] = []
    seen: set[str] = set()
    for raw_port in raw_ports:
        port = normalize_interface_name(raw_port)
        key = port.lower()
        if key in seen:
            continue
        seen.add(key)
        records.append(InputRecord(switch=host.strip(), port=port))
    return records


def _jinja_environment() -> Any:
    """Return the shared Jinja2 environment used for per-port templates.

    StrictUndefined is intentional: a typo such as ``{{ hostnmae }}`` must fail
    loudly instead of producing an incomplete Cisco command. Autoescaping is
    disabled because the output is Cisco CLI text, not HTML.
    """
    if Environment is None or StrictUndefined is None:
        raise RuntimeError(
            "Jinja2 is required for configuration generation. "
            "Install it with: pip install jinja2"
        )
    return Environment(
        undefined=StrictUndefined,
        autoescape=False,
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=False,
    )


def _validate_rendered_interface_body(rendered: str) -> str:
    """Normalize and safety-check the rendered interface-body commands.

    Structural commands are generated by Port_Config.py itself. They remain
    forbidden even when produced dynamically by a Jinja expression/conditional.
    This post-render validation prevents a template from escaping interface mode.
    """
    lines = [line.strip() for line in rendered.splitlines() if line.strip() and line.strip() != "!"]
    if not lines:
        raise ValueError("Rendered template is empty for this port")

    forbidden_patterns = [
        r"^interface\s+",
        r"^default\s+interface\s+",
        r"^(?:config|configure)\s+(?:t|terminal)$",
        r"^end$",
        r"^wr(?:ite\s+memory)?$",
        r"^exit$",
    ]
    for line in lines:
        if any(re.match(pattern, line, flags=re.I) for pattern in forbidden_patterns):
            raise ValueError(
                f"Rendered template contains structural command {line!r}. "
                "Keep only commands that belong under the interface; "
                "Port_Config adds interface/exit/end/wr automatically."
            )
    return "\n".join(lines)


def load_and_validate_template(path: Path) -> str:
    """Load and syntax-check a Jinja2 per-interface configuration template.

    The source may be completely static (plain text is valid Jinja2) or use
    variables/conditionals. Structural command validation is performed after
    rendering because Jinja expressions may generate different commands per port.
    """
    if not path.is_file():
        raise FileNotFoundError(f"Template not found: {path}")
    text = path.read_text(encoding="utf-8")
    if not text.strip():
        raise ValueError("Template is empty")

    env = _jinja_environment()
    try:
        env.parse(text)
    except JinjaTemplateSyntaxError as exc:
        raise ValueError(
            f"Jinja2 template syntax error in {path} at line {getattr(exc, 'lineno', '?')}: {exc}"
        ) from exc
    return text


def parse_interface_status(show_status: str, target_port: str) -> str:
    """Map one interface from ``show interfaces status`` to the internal status enum.

    The parser accepts both long and short interface naming. Non-interface lines
    such as headers are ignored safely instead of being treated as malformed
    interface names. If the requested port is not present, ``NOT_FOUND`` is
    returned; if the line is found but its state is unfamiliar, ``UNKNOWN`` is
    returned.
    """
    for raw_line in show_status.splitlines():
        line = raw_line.strip()
        if not line:
            continue

        first = line.split()[0]
        if not interface_token_matches(first, target_port):
            continue

        low = line.lower()
        if re.search(r"\berr-?disabled\b", low):
            return PORT_ERR_DISABLED
        if re.search(r"\bnotconnect\b|\bnot-connected\b", low):
            return PORT_NOT_CONNECTED
        if re.search(r"\bconnected\b", low):
            return PORT_CONNECTED
        if re.search(r"\bdisabled\b", low):
            return PORT_ADMIN_DOWN
        return PORT_UNKNOWN

    return PORT_NOT_FOUND


def extract_status_line(show_status: str, target_port: str) -> str:
    """Return the raw matching status line while safely ignoring CLI headers."""
    for raw in show_status.splitlines():
        line = raw.rstrip()
        parts = line.split()
        if not parts:
            continue

        if interface_token_matches(parts[0], target_port):
            return line

    return "PORT NOT FOUND IN show interfaces status"


def parse_running_interface_config(output: str) -> RunningConfigInfo:
    """Extract description, configured Access VLAN, and configured Voice VLAN.
    
    Missing explicit Access VLAN is represented as DEFAULT; missing Voice VLAN is
    represented as NONE. Raw output is retained for troubleshooting/evidence."""
    info = RunningConfigInfo(raw=output)
    for raw in output.splitlines():
        line = raw.strip()
        m = re.match(r"description\s+(.+)$", line, re.IGNORECASE)
        if m:
            info.description = m.group(1).strip()
            continue
        m = re.match(r"switchport\s+access\s+vlan\s+(\d+)$", line, re.IGNORECASE)
        if m:
            info.configured_access_vlan = m.group(1)
            continue
        m = re.match(r"switchport\s+voice\s+vlan\s+(\d+|none|dot1p|untagged)$", line, re.IGNORECASE)
        if m:
            value = m.group(1).upper()
            info.configured_voice_vlan = "NONE" if value == "NONE" else value
    return info


def _clean_vlan_token(value: str, *, voice: bool = False) -> str:
    """Normalize a VLAN token from Cisco operational output into a stable internal value."""
    value = (value or "").strip()
    if not value:
        return "NONE" if voice else "UNKNOWN"
    low = value.lower()
    if voice and low in {"none", "n/a", "unassigned"}:
        return "NONE"
    m = re.search(r"\b(\d+)\b", value)
    if m:
        return m.group(1)
    if voice and low in {"dot1p", "untagged"}:
        return low.upper()
    return "UNKNOWN"


def parse_switchport_output(output: str) -> SwitchportInfo:
    """Parse operational switchport fields required for VLAN validation.
    
    Only fields used by this tool are extracted; the raw output is preserved in the
    returned object for evidence and troubleshooting."""
    info = SwitchportInfo(raw=output)
    field_map = {
        "administrative mode": "administrative_mode",
        "operational mode": "operational_mode",
        "access mode vlan": "operational_access_vlan",
        "voice vlan": "operational_voice_vlan",
        "trunking native mode vlan": "trunk_native_vlan",
        "negotiation of trunking": "negotiation",
    }
    for raw in output.splitlines():
        if ":" not in raw:
            continue
        key, value = raw.split(":", 1)
        key = key.strip().lower()
        if key not in field_map:
            continue
        attr = field_map[key]
        value = value.strip()
        if attr == "operational_access_vlan":
            value = _clean_vlan_token(value)
        elif attr == "operational_voice_vlan":
            value = _clean_vlan_token(value, voice=True)
        elif attr == "trunk_native_vlan":
            value = _clean_vlan_token(value)
        setattr(info, attr, value or "UNKNOWN")
    return info




