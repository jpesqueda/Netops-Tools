def template_context(result: PortResult) -> dict[str, Any]:
    """Build the supported Jinja2 context for one port.

    Keep aliases intentionally explicit so templates remain readable and stable.
    New variables should be added here rather than scattered through rendering
    call sites.
    """
    detected_mac = ",".join(result.detected_macs) if result.detected_macs else "NONE"
    return {
        "hostname": result.switch,
        "switch": result.switch,
        "device": result.switch,
        "port": result.port,
        "interface": result.port,
        "expected_mac": result.expected_mac or "Not Provided",
        "detected_mac": detected_mac,
        "detected_macs": list(result.detected_macs),
        "port_status": result.port_status,
        "description": result.description,
        "access_vlan": result.final_access_vlan,
        "voice_vlan": result.final_voice_vlan,
        "configured_access_vlan": result.configured_access_vlan,
        "operational_access_vlan": result.operational_access_vlan,
        "configured_voice_vlan": result.configured_voice_vlan,
        "operational_voice_vlan": result.operational_voice_vlan,
    }


def render_template(template: str, result: PortResult) -> str:
    """Render one Jinja2 interface-body template for a specific port.

    StrictUndefined catches unknown variables. The rendered CLI is then checked
    to ensure the template did not create structural/global configuration commands.
    """
    env = _jinja_environment()
    try:
        rendered = env.from_string(template).render(**template_context(result))
    except JinjaTemplateError as exc:
        raise ValueError(
            f"Jinja2 rendering failed for {result.switch} {result.port}: {exc}"
        ) from exc
    return _validate_rendered_interface_body(rendered)


def comment_config_block(block: str) -> str:
    """Prefix every meaningful configuration line with `!` for manual-review safety."""
    lines: list[str] = []
    for line in block.splitlines():
        if not line or line.strip() == "!":
            lines.append("!")
        else:
            lines.append("!" + line)
    return "\n".join(lines)




