def build_device_config_text(switch: str, results: list[PortResult]) -> str:
    """Build one complete device section including post-save validation commands."""
    active_blocks = [r for r in results if r.config_block.strip()]
    lines = [f"Device_Name:{switch}", "config t", "!"]
    for index, result in enumerate(active_blocks):
        lines.append(result.config_block.rstrip())
        if index < len(active_blocks) - 1:
            lines.append("!")
    lines.extend(["end", "wr", "!"])

    # Validation commands intentionally appear after the configuration is saved.
    # They are also understood by --execute and are run as read-only commands.
    for result in results:
        lines.append(f"show interfaces {result.port} status")
        lines.append(f"show mac address-table interface {result.port}")
        lines.append("!")
    return "\n".join(lines).rstrip() + "\n"


def write_config_file(path: Path, results: Iterable[PortResult], switch_order: list[str]) -> None:
    """Write one AIO multifile containing all requested switches."""
    path.parent.mkdir(parents=True, exist_ok=True)
    by_switch: dict[str, list[PortResult]] = defaultdict(list)
    for result in results:
        by_switch[result.switch].append(result)
    sections = [build_device_config_text(sw, by_switch.get(sw, [])) for sw in switch_order if by_switch.get(sw)]
    path.write_text("\n".join(section.rstrip() for section in sections) + ("\n" if sections else ""), encoding="utf-8")



def write_device_config_files(
    results: Iterable[PortResult],
    switch_order: list[str],
    output_dir: Path | None = None,
) -> list[Path]:
    """Write one Config_<Device>.txt implementation file per switch."""
    target_dir = output_dir or Path(".")
    target_dir.mkdir(parents=True, exist_ok=True)
    by_switch: dict[str, list[PortResult]] = defaultdict(list)
    for result in results:
        by_switch[result.switch].append(result)

    generated: list[Path] = []
    for switch in switch_order:
        switch_results = by_switch.get(switch, [])
        if not switch_results:
            continue
        path = target_dir / f"Config_{sanitize_filename(switch)}.txt"
        path.write_text(build_device_config_text(switch, switch_results), encoding="utf-8")
        generated.append(path)
    return generated



