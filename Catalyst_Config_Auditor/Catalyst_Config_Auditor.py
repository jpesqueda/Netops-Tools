def parse_counter_tables(output):
    """Combine IOS-XE multi-section show interfaces counters tables by port.

    Each 'Port InOctets ...' and 'Port OutOctets ...' group is merged by
    exact interface name. Return None for unknown variants rather than
    incorrectly assigning counts to columns.
    """
    rows={};headers=['Port'];seen=0;active=None;unparsed=[]
    for raw in output.splitlines():
        line=raw.strip()
        if not line:continue
        cells=line.split()
        if cells[0].lower()=='port' and len(cells)>=3 and all(re.fullmatch(r'[A-Za-z][A-Za-z0-9_/-]*',v) for v in cells[1:]):
            active=cells[1:]
            for title in active:
                if title not in headers:headers.append(title)
            seen+=1
            continue
        if active and re.fullmatch(r'[A-Za-z][\w./:-]*\d+(?:/\d+)*',cells[0]) and len(cells)==len(active)+1:
            if all(re.fullmatch(r'[\d,]+|N/A|--|-',c,re.I) for c in cells[1:]):
                row=rows.setdefault(cells[0],{})
                for key,value in zip(active,cells[1:]):row[key]=int(value.replace(',','')) if re.fullmatch(r'[\d,]+',value) else value
                continue
        # Unknown CLI format must not be silently misrepresented as numeric columns.
        if active and cells and (re.match(r'^(?:Gi|Te|Twe|Fo|Hu|Eth|Fa)\d',cells[0],re.I)):
            unparsed.append(line)
    if not seen or not rows or unparsed:return None
    return headers,[[port]+[values.get(h,'') for h in headers[1:]] for port,values in rows.items()]


def generic_fixed_width_table(output):
    """Return a CLI table only when column boundaries are unambiguous.

    Using whitespace-delimited cells avoids accidental column shifting when
    device descriptions vary in length. If the header or data disagrees about
    column counts, use the lossless RAW fallback rather than guessing.
    """
    lines=output.splitlines()
    for i,header in enumerate(lines):
        if not re.search(r'\s{2,}',header.strip()):continue
        names=re.split(r'\s{2,}',header.strip())
        if not (2<=len(names)<=20) or any(len(n)>40 for n in names):continue
        candidates=[]
        for raw in lines[i+1:]:
            if not raw.strip():
                if candidates:break
                continue
            if re.fullmatch(r'\s*[-=]{4,}\s*',raw):continue
            vals=re.split(r'\s{2,}',raw.strip())
            if len(vals)!=len(names):break
            candidates.append(vals)
        if len(candidates)>=2:
            # Do not present partial multi-section output as complete.
            tail='\n'.join(lines[i+1+len(candidates):]).strip()
            if tail and re.search(r'(?mi)^\s*(?:Port|Interface|Neighbor)\s{2,}',tail):continue
            return names,candidates
    return None


def command_table(command,output):
    """Structured parser -> guarded generic parser -> lossless 2-column RAW."""
    c=re.sub(r'\s+',' ',command.lower().strip())
    if c in ('show ip interface brief','sh ip interface brief'):
        entries=[]
        for line in output.splitlines():
            parts=line.strip().split()
            # Account for variable-width 'administratively down' status.
            if len(parts)>=6 and parts[0].lower()!='interface':
                entries.append([parts[0],parts[1],parts[2],parts[3], ' '.join(parts[4:-1]),parts[-1]])
        if entries:return ['Interface','IP Address','OK?','Method','Status','Protocol'],entries
    if c in ('show interfaces description','show interface description','sh interfaces description'):
        entries=[]
        for line in output.splitlines():
            if not line.strip() or line.lstrip().lower().startswith('interface '):continue
            m=re.match(r'^\s*(\S+)\s+(administratively down|admin down|up|down|deleted)\s+(up|down|deleted)\s*(.*)$',line,re.I)
            if m:entries.append(list(m.groups()))
            else:entries.append([line.strip(),'','','UNPARSED - review raw output'])
        if entries:return ['Interface','Status','Protocol','Description'],entries
    if c in ('show interfaces status','show interface status','sh interfaces status'):
        entries=[]
        status_pat=r'(?:notconnect|connected|disabled|err-disabled|inactive|monitoring|suspended|sfpAbsent|xcvrAbsen|notpresent|faulty|up|down|unassigned|channelDown|onboard|secure-shutdown)'
        for raw in output.splitlines():
            line=raw.rstrip()
            if not line.strip() or re.match(r'^\s*Port\s+Name\s+Status\s+Vlan',line,re.I):continue
            m=re.match(r'^\s*(\S+)\s+(.*?)\s+('+status_pat+r')\s+(\S+)\s+(\S+)\s+(\S+)(?:\s+(.*))?\s*$',line,re.I)
            if m:
                port,name,status,vlan,duplex,speed,ptype=m.groups()
                entries.append([port,name.strip(),status,vlan,duplex,speed,(ptype or '').strip()])
            else:entries.append([line.strip(),'','','','','','UNPARSED - review raw output'])
        if entries:return ['Port','Name','Status','Vlan','Duplex','Speed','Type'],entries
    if c.startswith(('show interfaces counters','sh interfaces counters','show interface counters')):
        parsed=parse_counter_tables(output)
        if parsed:return parsed
    if c in ('show inventory','sh inventory'):
        rows=[];name=None;descr=None
        for line in output.splitlines():
            m=re.search(r'NAME:\s*"([^"]+)"\s*,\s*DESCR:\s*"([^"]*)"',line)
            if m:name,descr=m.groups()
            m=re.search(r'PID:\s*(\S+)\s*,\s*VID:\s*([^,]*)\s*,\s*SN:\s*(\S+)',line)
            if m:rows.append([name or '',descr or '',*m.groups()]);name=descr=None
        if rows:return ['Name','Description','PID','VID','Serial'],rows
    if c in ('show version','sh version'):
        rows=[]
        for line in output.splitlines():
            if any(key in line.lower() for key in ('uptime is','ios xe software','system image file','processor board id')):
                rows.append([line.strip()])
        if rows:return ['Version fact'],rows
    parsed=generic_fixed_width_table(output)
    if parsed:return parsed
    # Other IOS-XE commands are not necessarily tables (e.g. show running).
    # Return separate Excel columns for line number and exact text.
    return ['Line','Raw output'],[[i,line] for i,line in enumerate(output.splitlines(),1)] or [[1,'(empty output)']]

