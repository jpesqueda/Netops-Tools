def _ask_file(value, label):
    """Request an omitted path, including a flag supplied without a value."""
    if value:
        return Path(value).expanduser()
    try:
        answer=input(f'    {label}: ').strip().strip('"')
    except EOFError as exc:
        raise ValueError(f'{label} is required. Supply the path as a CLI argument.') from exc
    if not answer:
        raise ValueError(f'{label} cannot be empty')
    return Path(answer).expanduser()


def _related_file(template_path, yaml_path, explicit=None, generic='', legacy=()):
    """Locate a sibling input, preferring generic v1.3.2 filenames.

    Older backups remain usable without modifying their YAML files.
    """
    if explicit:
        candidate=Path(explicit).expanduser()
        if not candidate.is_file():
            raise FileNotFoundError(f'Input not found: {candidate}')
        return candidate
    names=[generic]+list(legacy)
    roots=[yaml_path.parent,template_path.parent]
    for root in roots:
        for name in names:
            candidate=root/name
            if candidate.is_file():return candidate
    raise FileNotFoundError(f'Missing {generic} next to the YAML/template. Use --interface-vars to specify it.')


def _load_yaml_any(path):
    """Load YAML safely, accepting any root type for generic Jinja2 rendering."""
    value=yaml.safe_load(path.read_text(encoding='utf-8-sig'))
    if value is None:
        raise ValueError(f'Empty YAML file: {path}')
    return value


def _jinja_context(value):
    """Mapping roots expose keys directly; other roots are available as data."""
    if isinstance(value, dict):
        if not all(isinstance(key,str) for key in value):
            raise ValueError('Top-level YAML mapping keys must be strings')
        result=dict(value)
        result.setdefault('data', value)
        return result
    return {'data': value}


def _merge_yaml_context(context, source):
    """Explicit extra YAML mappings override prior top-level keys."""
    values=_load_yaml_any(source)
    if not isinstance(values,dict) or not all(isinstance(key,str) for key in values):
        raise ValueError(f'Extra YAML must be a mapping with string keys: {source}')
    context.update(values)


def _existing_interface_sidecar(template_path, yaml_path):
    """Support older generated network templates without imposing a file on generic Jinja."""
    for directory in (yaml_path.parent, template_path.parent):
        for filename in ('var_interfaces.yaml','interface.yaml'):
            candidate=directory/filename
            if candidate.is_file():
                return candidate
    return None


def _create_destination(args, template_path, yaml_path, context):
    """Default output is generic; retain original Catalyst output for generated main template."""
    if args.output_file:
        return Path(args.output_file).expanduser()
    root=Path(args.output)
    if (template_path.name == 'template_main.j2' and
            yaml_path.name == 'var_main.yaml' and
            isinstance(context.get('hostname'),str) and context['hostname'].strip()):
        hostname=safe_filename(context['hostname'])
        return root/hostname/'Variables'/f'{hostname}_generated.cfg'
    return root/f'{safe_filename(template_path.stem)}_generated.txt'


def create_config(args):
    """Render any Jinja2 template using any primary YAML; no network assumptions."""
    banner('CONFIG GENERATOR')
    print('[+] Configuration Generator\n')
    tpath=_ask_file(args.template,'Jinja2 Template')
    vpath=_ask_file(args.variables,'Variables YAML')
    if not tpath.is_file():raise FileNotFoundError(f'Template not found: {tpath}')
    if not vpath.is_file():raise FileNotFoundError(f'Variables YAML not found: {vpath}')

    context=_jinja_context(_load_yaml_any(vpath))
    main_text=tpath.read_text(encoding='utf-8-sig')
    included_names=re.findall(r"\{%\s*include\s*['\"]([^'\"]+)['\"]", main_text)
    extras=[Path(value).expanduser() for value in args.extra_vars]
    # Backward compatibility for --interface-vars, but no *required* sidecar.
    if args.interface_vars:
        extras.append(Path(args.interface_vars).expanduser())
    elif ('template_interfaces.j2' in included_names and
          'interfaces' not in context):
        sidecar=_existing_interface_sidecar(tpath,vpath)
        if sidecar is not None:
            extras.append(sidecar)
    for extra in extras:
        if not extra.is_file():raise FileNotFoundError(f'Extra YAML not found: {extra}')
        _merge_yaml_context(context,extra)

    override=None
    if args.interface_template:
        override=Path(args.interface_template).expanduser()
        if not override.is_file():raise FileNotFoundError(f'Interface template not found: {override}')

    loader=FileSystemLoader(str(tpath.parent))
    if override is not None:
        # The --interface-template override is only for the standard generated
        # include. Custom templates keep their own includes and paths.
        included=[name for name in included_names if Path(name).name == 'template_interfaces.j2']
        if not included:
            raise ValueError('--interface-template requires an include of template_interfaces.j2')
        contents=override.read_text(encoding='utf-8-sig')
        loader=ChoiceLoader([DictLoader({name:contents for name in included}),loader])

    label=context.get('hostname')
    if not isinstance(label,str) or not label.strip():label=tpath.stem
    logname=safe_filename(label)
    logger,_=log_for(args.output,logname,'CREATE')
    try:
        logger.info('Jinja2 Template: %s',tpath)
        logger.info('Primary YAML: %s',vpath)
        for extra in extras:logger.info('Additional YAML: %s',extra)
        logger.info('Template override: %s',override if override else 'None')
        env=Environment(loader=loader,undefined=StrictUndefined,
                        autoescape=False,keep_trailing_newline=True)
        template=env.get_template(tpath.name)
        print('[+] Loading Jinja2 templates...      : PASS')
        print('[+] Loading YAML variables...        : PASS')
        rendered=template.render(**context)
        print('[+] Validating configuration...     : PASS')
        destination=_create_destination(args,tpath,vpath,context)
        save_text(destination,rendered,args.overwrite)
        logger.info('Template rendered: PASS | Output: %s',destination)
        print(f'[+] Saving generated file...       {destination.name} : CREATED')
        print('[+] Generation completed successfully.')
        print(f'\nFiles created in: {destination.parent.resolve()}')
        return 0
    except Exception:
        logger.exception('Create mode failed')
        raise
    finally:
        close_log(logger)

def main(argv=None):
    args=cli(argv)
    try:
        if args.create_config:return create_config(args)
        targets=get_targets(args)
        if not targets:raise ValueError('Empty device inventory')
        if args.collect:
            banner('COLLECT')
            cmd=args.cmd_file
            if not cmd:
                try:cmd=input('[+] Command file\n    Enter command file [cmd.txt]: ').strip() or 'cmd.txt'
                except EOFError:cmd='cmd.txt'
            commands=read_commands(cmd)
            print('\n[+] Loading device inventory...')
            if len(targets)==1:print(f'Device  : {targets[0]}')
            else:print(f'Devices : {len(targets)}')
            args._username=args.username or input('SSH Username: ').strip()
            args._password=args.password if args.password is not None else getpass('SSH Password: ')
            if not args._username:raise ValueError('SSH username required')
            failures=[];results=[]
            def worker(target):return online_collect(args,target,commands)
            with ThreadPoolExecutor(max_workers=args.workers) as pool:
                futures={pool.submit(worker,t):t for t in targets}
                for future in as_completed(futures):
                    target=futures[future]
                    try:
                        name,folder=future.result()
                        results.append((name,folder))
                        print('\n[+] Saving backup...')
                        print('[+] Generating Excel workbook...')
                        print(f'[+] {name} Collection completed.')
                        print(f'\nFiles created in: {folder.resolve()}')
                    except Exception as exc:
                        print(f'[!] {target}: {type(exc).__name__}: {exc}')
                        failures.append(target)
            if args.vars:
                for name,_ in results:
                    print('\n'+'-'*32)
                    banner('VARIABLE EXTRACTION')
                    offline_vars(args,name,read_selection(args.selection))
            return 1 if failures else 0
        if args.vars:
            banner('VARIABLE EXTRACTION')
            sel=read_selection(args.selection)
            bad=0
            for target in targets:
                try:offline_vars(args,target,sel)
                except Exception as exc:bad+=1;print(f'[!] {target}: {type(exc).__name__}: {exc}')
            return 1 if bad else 0
        if args.excel:
            banner('EXCEL')
            for target in targets:
                p=offline_excel(args,target)
                print(f'[+] {target} Excel created.\nFiles created in: {p.parent.resolve()}')
            return 0
        raise ValueError('No operation selected')
    except (OSError,ValueError,TemplateError,yaml.YAMLError) as exc:
        print(f'[ERROR] {type(exc).__name__}: {exc}',file=sys.stderr)
        if args.debug:traceback.print_exc()
        return 2

if __name__=='__main__':sys.exit(main())
